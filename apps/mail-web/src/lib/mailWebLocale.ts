export type MailEmptyVariant =
  | "inbox"
  | "sent"
  | "drafts"
  | "search"
  | "read"
  | "starred"
  | "trash"
  | "archive"
  | "spam";

export function getMailEmptyStateContent(
  translate: (key: string) => string,
  variant: MailEmptyVariant,
): { title: string; body: string; tips?: string[] } {
  const cap = variant.charAt(0).toUpperCase() + variant.slice(1);
  const title = translate(`empty${cap}Title`);
  const body = translate(`empty${cap}Body`);
  const tips: string[] = [];
  for (let i = 0; i < 4; i += 1) {
    const tip = translate(`empty${cap}Tip${i}`);
    if (tip === `empty${cap}Tip${i}`) {
      break;
    }
    tips.push(tip);
  }
  return { title, body, tips: tips.length ? tips : undefined };
}
